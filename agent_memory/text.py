"""Нормализация слов для поиска по памяти — одна на факты и журнал.

Память русская, а по-русски одну задачу дважды одинаково не формулируют: «инбаунде»
должно найти «инбаунда», «База» — «база».
"""


def fold(text: str) -> str:
    """Регистр не важен. `LIKE` в SQLite без ICU регистронезависим только для
    латиницы — для кириллицы сравниваем уже свёрнутые строки."""
    return text.casefold()


def stem(word: str) -> str:
    """Отрезать окончание: два последних символа, но не короче четырёх.

    ponytail: наивное отсечение, даёт ложные совпадения на коротких словах;
    snowballstemmer, если точность станет мешать.
    """
    return word if len(word) < 5 else word[: max(4, len(word) - 2)]
